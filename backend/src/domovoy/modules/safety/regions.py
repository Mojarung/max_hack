REGIONS: dict[str, Region] = {r.code: r for r in _REGIONS}


def normalize_code(code: str | None) -> str | None:
    """«ru-uly » → «RU-ULY»; пустое и не похожее на код ISO - None."""
    if not code:
        return None
    value = code.strip().upper()
    return value if 4 <= len(value) <= 8 and "-" in value else None


def region_name(code: str | None) -> str | None:
    region = REGIONS.get(normalize_code(code) or "")
    return region.name if region else None


def mchs_rss_url(code: str) -> str:
    """Лента «Оперативная информация» регионального сайта МЧС для кода региона."""
    region = REGIONS.get(normalize_code(code) or "")
    if region is None:
        raise KeyError(f"Неизвестный регион: {code}")
    return f"https://{region.mchs}.mchs.gov.ru{MCHS_RSS_PATH}"
